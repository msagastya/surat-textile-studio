// Nearest atlas color to an [r,g,b] triple (squared-euclidean in RGB).
export function nearestNedColor(rgb) {
  let best = NED_ATLAS[0], bd = Infinity;
  for (const c of NED_ATLAS) {
    const d = (c.rgb[0]-rgb[0])**2 + (c.rgb[1]-rgb[1])**2 + (c.rgb[2]-rgb[2])**2;
    if (d < bd) { bd = d; best = c; }
  }
  return best;
}
